"""Build the static site from src/ into the repo root.

    python3 tools/build.py           write every generated file
    python3 tools/build.py --check   change nothing; fail if a generated file is stale or
                                     orphaned, a client name appears in a served or source
                                     file, a ™ lands inside an attribute, a {{ or a plain
                                     http:// URL is left, security.txt has expired, or a
                                     [PLACEHOLDER] is still showing (that one fails on
                                     purpose until the owner supplies the values)

Standard library only. What it does:
  * wraps each page body in src/pages/ with the shared head, header and footer
  * writes CSS custom properties from src/tokens.json, then joins src/css/*.css
    into assets/css/site.css
  * expands motif placeholders into the design's inline SVG pattern bands (src/motifs/)
  * puts ™ after the first visible mention of each name in config.json "trademarks"
  * adds ?v=<content hash> to the CSS and JS URLs, so new HTML never pairs with stale assets
  * writes redirect pages for retired URLs, sitemap.xml, robots.txt and security.txt

Generated files are committed, because GitHub Pages serves this branch as it is.
"""

import datetime
import hashlib
import html
import html.parser
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

PLACEHOLDER = re.compile(r"\[[A-Z0-9][A-Z0-9’' \-]*[A-Z0-9]\]")

RAAT_NEUTRALS = {"ground", "surface", "surface-raised", "ink", "text", "text-muted", "rule", "rule-strong"}

MOTIFS = ["sangam", "gargi", "birbal", "sutradhar", "margdarshak", "phala", "sandesh", "darshan"]

GENERATED_NOTE = "Generated by tools/build.py from src/. Edit the source, not this file."


def read(path):
    return (SRC / path).read_text(encoding="utf-8")


def load_json(path):
    return json.loads(read(path))


def fill(template, values):
    """Replace {{key}} with values[key]. Unknown keys are an error, so typos surface."""
    def sub(match):
        key = match.group(1)
        if key not in values:
            raise KeyError(f"unknown template key {{{{{key}}}}}")
        return str(values[key])
    return re.sub(r"\{\{\s*([^{}\s]+)\s*\}\}", sub, template)


def html_safe(value):
    """Escape a config value for HTML text or a double-quoted attribute (&, <, >, ").
    Single quotes are left alone so the CSP stays readable; every {{key}} that sits in an
    attribute is double-quoted, which render_page enforces."""
    return html.escape(str(value), quote=False).replace('"', "&quot;")


def json_safe(value):
    """Escape a config value for the inside of a JSON string in a <script> block."""
    return (json.dumps(str(value), ensure_ascii=False)[1:-1]
            .replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026"))


SINGLE_QUOTED_KEY = re.compile(r"=\s*'[^'<>]*\{\{")


def check_quoting(name, template):
    """A {{key}} inside a single-quoted attribute would not be safe with html_safe."""
    match = SINGLE_QUOTED_KEY.search(template)
    if match:
        raise ValueError(f"{name}: put {{{{key}}}} attributes in double quotes: …{match.group(0)}")


def config_problems(config):
    """Values that would be unsafe or broken wherever the templates put them."""
    problems = []
    for key in ("site_url",):
        if not re.fullmatch(r"https://[\w.-]+", config[key]):
            problems.append(f"{key} should be https://host with no trailing slash")
    if not (PLACEHOLDER.fullmatch(config["booking_url"]) or re.fullmatch(r"https://\S+", config["booking_url"])):
        problems.append("booking_url should be an https:// link")
    for key in ("contact_email", "security_contact"):
        if not re.fullmatch(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+", config[key]):
            problems.append(f"{key} does not look like an email address")
    return problems


# ---------------------------------------------------------------- tokens and CSS

def tokens_css(tokens):
    lines = [f"/* {GENERATED_NOTE} Tokens: src/tokens.json (Dattamsha v{tokens['version']}). */",
             ":root {"]
    for tok in tokens["color"]["tokens"]:
        value = tok["value"]
        if isinstance(value, dict):
            value = value["light"]
        ref = re.fullmatch(r"\{([a-z-]+)\}", value)
        if ref:
            value = f"var(--{ref.group(1)})"
        lines.append(f"  --{tok['name']}: {value};")
    # Raat (dark theme) neutrals, for the few panels drawn in the dark theme (the SQL card).
    for tok in tokens["color"]["tokens"]:
        if tok["name"] in RAAT_NEUTRALS and isinstance(tok["value"], dict):
            lines.append(f"  --{tok['name']}-raat: {tok['value']['dark']};")
    for role, stack in tokens["type"]["families"].items():
        lines.append(f"  --font-{role}: {stack};")
    for tok in tokens["spacing"]["tokens"]:
        lines.append(f"  --{tok['name']}: {tok['value']};")
    for tok in tokens["radius"]["tokens"]:
        lines.append(f"  --{tok['name']}: {tok['value']};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def site_css(tokens):
    parts = [tokens_css(tokens)]
    for path in sorted((SRC / "css").glob("*.css")):
        parts.append(f"\n/* ---- {path.name} ---- */\n" + path.read_text(encoding="utf-8"))
    return "".join(parts)


# ---------------------------------------------------------------- motifs

# Band height -> the design's patternTransform scale on its 48px tile (identical in every
# design file). Drawing the bands exactly as the design does keeps them pixel-identical.
MOTIF_SCALE = {12: "0.25", 14: "0.3", 16: "0.33", 18: "0.38", 20: "0.42", 22: "0.46", 24: "0.5"}
MOTIF_TAG = re.compile(r'<(div|span) class="([^"]*\bmotif\b[^"]*)" aria-hidden="true"></\1>')


def motif_patterns(tokens):
    """{name: (tile width, pattern body, pigment, tint, on)} from src/motifs/*.svg."""
    colours = {t["name"]: (t["value"]["light"] if isinstance(t["value"], dict) else t["value"])
               for t in tokens["color"]["tokens"]}
    out = {}
    for name in MOTIFS:
        svg = read(f"motifs/{name}.svg")
        pattern = re.search(r'<pattern[^>]*width="(\d+)"[^>]*>(.*?)</pattern>', svg, re.S)
        out[name] = (pattern.group(1), " ".join(pattern.group(2).split()),
                     colours[name], colours[f"{name}-tint"], colours[f"{name}-on"])
    return out


def inline_motifs(markup, patterns):
    """Replace each <div|span class="motif motif--NAME [motif--on] [motif--H]" aria-hidden="true">
    placeholder with the design's inline SVG band. Pattern ids are unique per page."""
    counter = [0]

    def expand(match):
        classes = match.group(2).split()
        names = [c[len("motif--"):] for c in classes if c[len("motif--"):] in patterns]
        if len(names) != 1:
            raise ValueError(f"motif needs exactly one product class: {match.group(0)}")
        heights = [int(c[len("motif--"):]) for c in classes if re.fullmatch(r"motif--\d+", c)]
        height = heights[0] if heights else 24
        if height not in MOTIF_SCALE:
            raise ValueError(f"no design scale for a {height}px motif band")
        on = "motif--on" in classes
        extra = [c for c in classes if c != "motif" and not c.startswith("motif--")]
        width, body, pigment, tint, on_colour = patterns[names[0]]
        counter[0] += 1
        pid = f"m{counter[0]}"
        if on:
            body, ground, opacity = body.replace(pigment, on_colour), pigment, "0.38"
        else:
            ground, opacity = tint, "1"
        cls = " ".join(["motif"] + extra)
        return (f'<svg class="{cls}" aria-hidden="true" width="100%" height="{height}">'
                f'<defs><pattern id="{pid}" width="{width}" height="48" patternUnits="userSpaceOnUse" '
                f'patternTransform="scale({MOTIF_SCALE[height]})">{body}</pattern></defs>'
                f'<rect width="100%" height="100%" fill="{ground}"/>'
                f'<rect width="100%" height="100%" fill="url(#{pid})" opacity="{opacity}"/></svg>')

    markup = MOTIF_TAG.sub(expand, markup)
    left = re.search(r'<[^>]*class="[^"]*\bmotif--(?:' + "|".join(MOTIFS) + r')\b[^>]*>', markup)
    if left:
        raise ValueError("motif placeholder not expanded (write it exactly as "
                         '<div class="motif motif--NAME" aria-hidden="true"></div>): ' + left.group(0))
    return markup


# ---------------------------------------------------------------- trademarks

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
NO_MARK = {"head", "script", "style", "svg", "pre", "code", "title", "textarea", "template", "noscript", "option"}
# Elements whose text is never the first thing a visitor sees: `hidden` content, content
# marked data-no-tm, and the home-page demo regions that home.js hides or replaces at load
# (the Birbal steps and the Gargi answer box).
NO_MARK_ATTRS = {"hidden", "data-no-tm", "data-steps", "data-answer-box"}
NO_MARK_CLASSES = {"visually-hidden"}

_QUOTED = r"""(?:[^>"']|"[^"]*"|'[^']*')*"""
TOKEN = re.compile(r"<!--.*?-->"
                   r"|<(?P<raw>script|style|textarea|title)\b" + _QUOTED + r">.*?</(?P=raw)\s*>"
                   r"|</?[a-zA-Z!]" + _QUOTED + ">", re.S | re.I)
ATTR = re.compile(r"""([^\s"'>/=]+)(?:\s*=\s*("[^"]*"|'[^']*'|[^\s>]+))?""")


def tag_attrs(token):
    """{name: value} for a start tag; names lowercased, values unquoted (not unescaped)."""
    body = re.sub(r"^<[a-zA-Z][\w-]*", "", token)[:-1]
    out = {}
    for name, value in ATTR.findall(body):
        out[name.lower()] = value[1:-1] if value[:1] in "\"'" and value else value
    return out


def add_trademarks(doc, names):
    """Put ™ after the first visible mention of each trademarked name on the page.
    Text in <head>, scripts, SVG, code, form fields, templates, <noscript>, and anything
    under an element in NO_MARK_ATTRS / NO_MARK_CLASSES is left alone, so the mark lands
    on the first mention a visitor actually sees. Attribute values are never touched."""
    pattern = re.compile(r"\b(" + "|".join(map(re.escape, names)) + r")\b(?!™)")
    marked = set()
    stack = []          # (tag, skips) for open elements
    out = []

    def mark(match):
        name = match.group(1)
        if name in marked:
            return name
        marked.add(name)
        return name + "™"

    def text(chunk):
        if chunk and not any(skip for _, skip in stack):
            chunk = pattern.sub(mark, chunk)
        out.append(chunk)

    pos = 0
    for m in TOKEN.finditer(doc):
        text(doc[pos:m.start()])
        pos = m.end()
        token = m.group(0)
        out.append(token)
        if token.startswith("<!") or m.group("raw"):
            continue                       # comment, doctype, or a whole script/style/textarea/title
        if token.startswith("</"):
            tag = token[2:-1].strip().lower()
            if any(t == tag for t, _ in stack):
                while stack and stack.pop()[0] != tag:
                    pass
            continue
        tag = re.match(r"<([a-zA-Z][\w-]*)", token).group(1).lower()
        if tag in VOID or token.endswith("/>"):
            continue
        attrs = tag_attrs(token)
        skips = (tag in NO_MARK or bool(NO_MARK_ATTRS & attrs.keys())
                 or bool(NO_MARK_CLASSES & set(attrs.get("class", "").split())))
        stack.append((tag, skips))
    text(doc[pos:])
    return "".join(out)


class _AttrScan(html.parser.HTMLParser):
    def __init__(self, needle):
        super().__init__(convert_charrefs=True)
        self.needle, self.hits = needle, []

    def handle_starttag(self, tag, attrs):
        for name, value in attrs:
            if value and self.needle in value:
                self.hits.append((self.getpos()[0], f"<{tag} {name}=…>"))

    handle_startendtag = handle_starttag


def marks_in_attributes(doc):
    scan = _AttrScan("™")
    scan.feed(doc)
    return scan.hits


